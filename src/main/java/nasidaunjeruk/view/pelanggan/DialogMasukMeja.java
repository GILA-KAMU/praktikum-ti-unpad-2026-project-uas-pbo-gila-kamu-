    /** Tampilkan dialog dan tunggu sampai ditutup. Null bila batal. */
    public Meja tampilkan() {
        setVisible(true);
        return hasil;
    }

    private void scanKamera() {
        String isi = new DialogScanQr(this).tampilkan();
        if (isi != null) masukDariQr(isi);
    }

    private void pilihGambar() {
        JFileChooser pilih = new JFileChooser(folderTerakhir);
        pilih.setDialogTitle("Pilih gambar QR meja");
        pilih.setFileFilter(new FileNameExtensionFilter("Gambar (PNG, JPG, BMP, GIF)", "png", "jpg", "jpeg", "bmp", "gif"));
        if (pilih.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) return;
        File file = pilih.getSelectedFile();
        folderTerakhir = file.getParentFile();
        try {
            BufferedImage gambar = ImageIO.read(file);
            if (gambar == null) {
                Ui.error(this, "File itu bukan gambar.");
                return;
            }
            String isi = QrCode.baca(gambar);
            if (isi == null) {
                Ui.error(this, "Tidak ada QR code yang terbaca di gambar itu.");
                return;
            }
            masukDariQr(isi);
        } catch (IOException e) {
            Ui.error(this, "Gambar gagal dibuka: " + e.getMessage());
        }
    }

    /** Cocokkan nomor meja dan token dari QR ke database. */
    private void masukDariQr(String isi) {
        QrCode.KodeMeja k = QrCode.bacaIsiMeja(isi);
        if (k == null) {
            Ui.error(this, "QR code ini bukan QR meja Nasi Daun Jeruk.");
            return;
        }
        try {
            Meja m = new MejaDAO().findByNomorDanToken(k.nomor(), k.token());
            if (m == null) {
                Ui.error(this, "QR meja " + k.nomor() + " sudah tidak berlaku.\nMinta QR terbaru ke pelayan.");
                return;
            }
            hasil = m;
            dispose();
        } catch (RuntimeException e) {
            Ui.tangani(this, e);
        }
    }

