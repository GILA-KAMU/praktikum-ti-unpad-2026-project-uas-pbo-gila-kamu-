    PanelKeranjang(FramePelanggan frame) {
        this.frame = frame;
        initComponents();
        Ui.aturTabel(tblKeranjang, model);
        Ui.lebarKolom(tblKeranjang, 260, 200, 90, 60, 100);
        txtNama.putClientProperty("JTextField.placeholderText", "Boleh dikosongkan");
        txtCatatan.putClientProperty("JTextField.placeholderText", "Contoh: pedas banget");
    }

    @Override
    public void segarkan() {
        Keranjang k = frame.getKeranjang();
        model.muat(k.getItems());
        lblTotal.setText(Format.rupiah(k.hitungTotal()));
        boolean kosong = k.isKosong();
        lblKosong.setVisible(kosong);
        btnPesan.setEnabled(!kosong);
        btnHapus.setEnabled(!kosong);
        btnKosongkan.setEnabled(!kosong);
    }

    void bersihkanInfo() {
        txtNama.setText("");
        txtCatatan.setText("");
    }

    private void hapusTerpilih() {
        int baris = tblKeranjang.getSelectedRow();
        if (baris < 0) {
            Ui.info(this, "Pilih item yang mau dihapus dulu.");
            return;
        }
        frame.getKeranjang().hapusItem(model.item(baris).getKey());
        frame.keranjangBerubah();
        frame.kabari("Item dihapus dari keranjang.");
    }

    private void kosongkan() {
        if (Ui.konfirmasi(this, "Kosongkan seluruh keranjang?")) {
            frame.getKeranjang().kosongkan();
            bersihkanInfo();
            frame.keranjangBerubah();
        }
    }

    /** Model tabel keranjang. Hanya kolom Jumlah yang bisa diedit. */
    private class ModelKeranjang extends AbstractTableModel {

        private final String[] kolom = {"Menu", "Catatan", "Harga", "Jumlah", "Subtotal"};
        private List<DetailPesanan> items = new ArrayList<>();

        void muat(List<DetailPesanan> baru) {
            items = baru;
            fireTableDataChanged();
        }

        DetailPesanan item(int baris) { return items.get(baris); }

        @Override public int getRowCount() { return items.size(); }
        @Override public int getColumnCount() { return kolom.length; }
        @Override public String getColumnName(int c) { return kolom[c]; }
        @Override public Class<?> getColumnClass(int c) { return c == 3 ? Integer.class : String.class; }
        @Override public boolean isCellEditable(int r, int c) { return c == 3; }

        @Override
        public Object getValueAt(int r, int c) {
            DetailPesanan d = items.get(r);
            return switch (c) {
                case 0 -> d.getMenu().getNamaMenu();
                case 1 -> d.getCatatanItem();
                case 2 -> Format.rupiah(d.getMenu().getHarga());
                case 3 -> d.getJumlah();
                default -> Format.rupiah(d.hitungSubtotal());
            };
        }

        @Override
        public void setValueAt(Object nilai, int r, int c) {
            if (c != 3 || !(nilai instanceof Integer jumlah)) return;
            frame.getKeranjang().ubahJumlah(items.get(r).getKey(), jumlah);
            // Tunggu editor tabel selesai sebelum tabel dimuat ulang
            SwingUtilities.invokeLater(frame::keranjangBerubah);
        }
    }

