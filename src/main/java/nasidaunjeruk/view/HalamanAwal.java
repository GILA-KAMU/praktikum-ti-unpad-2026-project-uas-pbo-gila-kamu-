    private void bukaPelanggan() {
        Meja meja = new DialogMasukMeja(this).tampilkan();
        if (meja != null) {
            new FramePelanggan(meja).setVisible(true);
        }
    }

    private void bukaPegawai() {
        Pengguna p = new DialogLogin(this).tampilkan();
        if (p != null) {
            new FrameDashboard(p).setVisible(true);
        }
    }

