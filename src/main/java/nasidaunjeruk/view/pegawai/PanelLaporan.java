    @Override
    public void segarkan() {
        boolean perBulan = tglBulanan.isSelected();
        List<BarisLaporan> baris;
        List<MenuTerlaris> terlaris;
        try {
            baris = admin.lihatLaporan(perBulan ? "bulanan" : "harian");
            terlaris = new PesananDAO().menuTerlaris(5);
        } catch (RuntimeException e) {
            Ui.tangani(this, e);
            return;
        }
        modelPenjualan.setColumnIdentifiers(new Object[]{perBulan ? "Bulan" : "Tanggal", "Jumlah pesanan", "Pendapatan"});
        modelPenjualan.setRowCount(0);
        int jumlah = 0;
        double uang = 0;
        for (BarisLaporan b : baris) {
            modelPenjualan.addRow(new Object[]{b.periode(), b.jumlahPesanan(), Format.rupiah(b.total())});
            jumlah += b.jumlahPesanan();
            uang += b.total();
        }
        lblTotal.setText(baris.isEmpty() ? "Belum ada penjualan."
                : "Total: " + jumlah + " pesanan · " + Format.rupiah(uang));

        modelTerlaris.setRowCount(0);
        for (MenuTerlaris t : terlaris) {
            modelTerlaris.addRow(new Object[]{t.namaMenu(), t.terjual()});
        }
    }

