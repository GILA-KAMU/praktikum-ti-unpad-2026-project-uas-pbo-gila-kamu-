    @Override
    public void segarkan() {
        try {
            model.setRowCount(0);
            for (Pengguna p : new PenggunaDAO().findAll()) {
                String peran = p.getRole().substring(0, 1).toUpperCase() + p.getRole().substring(1);
                model.addRow(new Object[]{p.getNama(), p.getUsername(), peran});
            }
        } catch (RuntimeException e) {
            Ui.tangani(this, e);
        }
    }

    private void tambah() {
        String u = txtUsername.getText().trim();
        try {
            admin.tambahKasir(txtNama.getText(), u, new String(txtPassword.getPassword()));
            Ui.info(this, "Akun kasir " + u + " dibuat.");
            txtNama.setText("");
            txtUsername.setText("");
            txtPassword.setText("");
            segarkan();
        } catch (DataException e) {
            Ui.error(this, e.isPelanggaranData() ? "Username itu sudah dipakai." : e.getMessage());
        } catch (RuntimeException e) {
            Ui.tangani(this, e);
        }
    }

